"""Stateless public product demo. Never reads tenant or patient data."""
from fastapi import APIRouter
from pydantic import BaseModel, Field

router = APIRouter(prefix="/api/public/demo", tags=["Публичное демо"])

class DemoMessage(BaseModel):
    message: str = Field(min_length=1, max_length=1000)

@router.post("/chat")
def public_demo(payload: DemoMessage):
    text = payload.message.casefold()
    if any(s in text for s in ("бол", "лекар", "диагноз", "лечить", "температур")):
        reply = "Медицинские вопросы нужно обсудить со стоматологом. Я помогаю с организацией визита и могу передать обращение администратору. В этом примере никаких обращений в клинику не отправляется."
    elif any(s in text for s in ("цен", "сто", "прайс", "руб")):
        reply = "Пример прайса демонстрационной клиники: консультация — 1 500 ₽, профессиональная гигиена — 5 500 ₽. Это иллюстрация работы: в кабинете подключённой клиники цены берутся из её собственного справочника."
    elif any(s in text for s in ("запис", "время", "окно", "приём", "прием")):
        reply = "В рабочем кабинете я сначала уточняю услугу и филиал, затем запрашиваю свободное время из базы. После вашего подтверждения создаётся запись, пациент и карточка CRM. Для настоящего теста откройте Smile Avenue в Dev Stand. Здесь запись не создаётся."
    elif any(s in text for s in ("человек", "администратор", "оператор")):
        reply = "В рабочем чате можно нажать «Позвать администратора»: сотрудник получит задачу и перехватит диалог с сохранением истории. В этом примере отправка сотруднику отключена."
    elif any(s in text for s in ("ноч", "работ", "часы", "выход")):
        reply = "Администратор DentFlow доступен, пока работает ваш сервер. Он использует заданные клиникой часы приёма и предлагает только доступные слоты. Вы можете самостоятельно проверить это в тестовом стенде."
    else:
        reply = "Здравствуйте! Я демонстрационный администратор DentFlow. Спросите о ценах, записи, рабочем времени или передаче человеку. Этот пример работает без внешней нейросети и не сохраняет вашу переписку."
    return {"reply": reply, "mode": "demo", "disclaimer": "Интерактивный пример. Запись не создаётся; данные не отправляются внешней LLM."}
